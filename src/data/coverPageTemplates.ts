export function createCoverPersonalInfoFromCV(cv?: CVDocument | null): CoverPagePersonalInfo {
  if (!cv) return { ...DEFAULT_COVER_PERSONAL_INFO };
  const p = cv.personalInformation;
  return {
    fullName: p.fullName || DEFAULT_COVER_PERSONAL_INFO.fullName,
    professionalTitle: p.professionalTitle || DEFAULT_COVER_PERSONAL_INFO.professionalTitle,
    professionalSubtitle: cv.cvTitle || DEFAULT_COVER_PERSONAL_INFO.professionalSubtitle,
    email: p.email || '',
    phone: p.phone || '',
    location: p.location || '',
    website: p.website || '',
    linkedin: p.linkedin || '',
    cvTitle: 'CURRICULUM VITAE',
    tagline: cv.careerObjective
      ? cv.careerObjective.slice(0, 140)
      : DEFAULT_COVER_PERSONAL_INFO.tagline,
    careerSpecialty:
      cv.skills.length > 0
        ? cv.skills
            .slice(0, 4)
            .map((s) => s.name)
            .join(' · ')
        : DEFAULT_COVER_PERSONAL_INFO.careerSpecialty,
    introduction:
      cv.professionalSummary || DEFAULT_COVER_PERSONAL_INFO.introduction,
    documentDate: new Date().toLocaleDateString('en-US', { month: 'long', year: 'numeric' }),
    targetOrganization: '',
  };
}

function el(
  partial: Partial<CoverCanvasElement> &
    Pick<CoverCanvasElement, 'id' | 'type' | 'label' | 'x' | 'y' | 'width' | 'height'>
): CoverCanvasElement {
  return {
    zIndex: 10,
    opacity: 1,
    rotation: 0,
    locked: false,
    style: {},
    ...partial,
  };
}

interface TemplateSeedInput {
  templateId: string;
  templateName: string;
  category: CoverPageCategory;
  description: string;
  featured?: boolean;
  scheme: CoverColorScheme;
  fontFamily: CoverPageFontFamily;
  headingFontFamily: CoverPageFontFamily;
  alignment: 'left' | 'center' | 'right';
  backgroundConfiguration: CoverBackgroundConfig;
  elements: CoverCanvasElement[];
  sampleOverrides?: Partial<CoverPagePersonalInfo>;
}

function makeTemplate(seed: TemplateSeedInput): CoverPageTemplate {
  const designConfiguration: CoverPageDesignConfiguration = {
    colorSchemeName: seed.scheme.name,
    primaryColor: seed.scheme.primary,
    secondaryColor: seed.scheme.secondary,
    accentColor: seed.scheme.accent,
    textColor: seed.scheme.text,
    mutedTextColor: seed.scheme.muted,
    fontFamily: seed.fontFamily,
    headingFontFamily: seed.headingFontFamily,
    alignment: seed.alignment,
    elements: seed.elements,
  };

  return {
    templateId: seed.templateId,
    templateName: seed.templateName,
    category: seed.category,
    description: seed.description,
    designConfiguration,
    previewConfiguration: {
      backgroundConfiguration: seed.backgroundConfiguration,
      defaultPageSize: 'A4',
      featured: Boolean(seed.featured),
      samplePersonalInfo: {
        ...DEFAULT_COVER_PERSONAL_INFO,
        ...seed.sampleOverrides,
      },
    },
    status: 'published',
  };
}

