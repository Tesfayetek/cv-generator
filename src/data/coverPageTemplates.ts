export function createCoverPageFromTemplate(
  userId: string,
  template: CoverPageTemplate,
  cv?: CVDocument | null,
  customTitle?: string
): CoverPageDocument {
  const now = new Date().toISOString();
  const personalInformation = createCoverPersonalInfoFromCV(cv);

  // Clone design & background cleanly so edits never mutate template definitions
  const designConfiguration: CoverPageDesignConfiguration = JSON.parse(
    JSON.stringify(template.designConfiguration)
  );
  const backgroundConfiguration: CoverBackgroundConfig = JSON.parse(
    JSON.stringify(template.previewConfiguration.backgroundConfiguration)
  );

  // If the CV already has a profile photo, populate photo elements cleanly
  const uploadedImages: CoverPageDocument['uploadedImages'] = {};
  if (cv?.personalInformation?.photoUrl) {
    uploadedImages.profilePhoto = cv.personalInformation.photoUrl;
    designConfiguration.elements = designConfiguration.elements.map((elItem) =>
      elItem.type === 'photo' ? { ...elItem, src: cv.personalInformation.photoUrl } : elItem
    );
  }

  return {
    coverPageId: `cp_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`,
    userId,
    cvId: cv?.cvId || '',
    templateId: template.templateId,
    title:
      customTitle ||
      (cv ? `${cv.cvTitle} — Cover Page` : `${template.templateName} Cover`),
    personalInformation,
    designConfiguration,
    backgroundConfiguration,
    uploadedImages,
    pageSize: template.previewConfiguration.defaultPageSize || 'A4',
    createdAt: now,
    updatedAt: now,
  };
}
