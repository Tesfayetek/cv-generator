export function createNewCVDocument(
  userId: string,
  templateId: string,
  title = 'Untitled Professional CV',
  designOverrides?: DesignConfiguration,
  prefillFromSample = false
): CVDocument {
  const now = new Date().toISOString();
  const cvId = `cv_${Date.now()}_${Math.random().toString(36).slice(2, 8)}`;

  if (prefillFromSample) {
    const sample = SAMPLE_CV_PROFILES.executive;
    return {
      ...sample,
      cvId,
      userId,
      cvTitle: title,
      selectedTemplateId: templateId,
      designOverrides,
      createdAt: now,
      updatedAt: now,
    };
  }

  return {
    cvId,
    userId,
    cvTitle: title,
    personalInformation: {
      fullName: '',
      professionalTitle: '',
      email: '',
      phone: '',
      location: '',
      linkedin: '',
      website: '',
      photoUrl: '',
    },
    professionalSummary: '',
    careerObjective: '',
    workExperience: [],
    education: [],
    skills: [],
    certifications: [],
    languages: [],
    projects: [],
    awards: [],
    publications: [],
    volunteerExperience: [],
    references: [],
    sectionOrder: [...DEFAULT_SECTION_ORDER],
    hiddenSections: [],
    sectionTitles: { ...DEFAULT_SECTION_TITLES },
    selectedTemplateId: templateId,
    designOverrides,
    atsMode: false,
    createdAt: now,
    updatedAt: now,
  };
}
