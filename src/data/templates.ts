import type {
  CVSectionKey,
  CVTemplate,
  ColorConfiguration,
  LayoutConfiguration,
  PageConfiguration,
  TemplateCategory,
  TypographyConfiguration,
} from '../types/cv';

interface TemplateSeedInput {
  id: string;
  name: string;
  category: TemplateCategory;
  profession: string;
  description: string;
  atsFriendly: boolean;
  popularity: number;
  sampleProfileKey: 'executive' | 'ngo' | 'academic' | 'tech' | 'graduate';
  layout: Partial<LayoutConfiguration>;
  colors: Partial<ColorConfiguration> & { primary: string; secondary: string; presetName: string };
  typography: Partial<TypographyConfiguration>;
  page?: Partial<PageConfiguration>;
  sectionOrder?: CVSectionKey[];
}

function buildTemplate(seed: TemplateSeedInput): CVTemplate {
  const layout: LayoutConfiguration = {
    structure: 'one-column',
    sidebarWidth: 32,
    headerStyle: 'left-aligned',
    showPhoto: false,
    photoShape: 'rounded',
    sectionHeadingStyle: 'underline',
    bulletStyle: 'disc',
    skillDisplay: 'tags',
    timelineStyle: 'none',
    decorativeAccent: 'none',
    showPageNumbers: true,
    headerText: '',
    footerText: '',
    sidebarSections: ['skills', 'languages', 'certifications', 'awards'],
    ...seed.layout,
  };

  const colors: ColorConfiguration = {
    accent: '#EAF2FB',
    background: '#FFFFFF',
    sidebarBg: '#F4F7FB',
    headerBg: seed.colors.primary,
    headerText: '#FFFFFF',
    text: '#1E293B',
    mutedText: '#475569',
    border: '#CBD5E1',
    ...seed.colors,
  };

  const typography: TypographyConfiguration = {
    fontFamily: 'Lato',
    headingFontFamily: 'Montserrat',
    nameSize: 25,
    headingSize: 12,
    bodySize: 10,
    fontWeight: '400',
    lineHeight: 1.45,
    letterSpacing: 0,
    ...seed.typography,
  };

  const page: PageConfiguration = {
    size: 'A4',
    marginTop: 15,
    marginRight: 16,
    marginBottom: 15,
    marginLeft: 16,
    sectionSpacing: 14,
    explicitPageBreaks: [],
    ...seed.page,
  };

  const defaultSectionOrder: CVSectionKey[] = seed.sectionOrder || [
    'summary',
    'experience',
    'education',
    'skills',
    'certifications',
    'projects',
    'languages',
    'awards',
    'publications',
    'volunteer',
    'references',
  ];

  return {
    templateId: seed.id,
    name: seed.name,
    category: seed.category,
    profession: seed.profession,
    description: seed.description,
    atsFriendly: seed.atsFriendly,
    tier: 'free',
    popularityScore: seed.popularity,
    layoutConfiguration: layout,
    colorConfiguration: colors,
    typographyConfiguration: typography,
    previewConfiguration: {
      page,
      defaultSectionOrder,
      sampleProfileKey: seed.sampleProfileKey,
    },
    status: 'published',
  };
}

